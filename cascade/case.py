"""Build an OpenFOAM case: geometry -> Gmsh mesh -> template fill -> gmshToFoam ->
patch types -> createPatch (cyclics) -> checkMesh.

    from cascade.case import load_config, build_case
    cfg = load_config("configs/base.json")
    meta = build_case(cfg, "runs/base")

Why the case is generated by code and not edited by hand
  * Every case (3 mesh levels, 7 geometries) must differ ONLY in the parameter I changed, so each one is written from
    the same case_template/ with placeholders (@NAME@) filled from one JSON config. Nothing is clicked together.
  * Inlet turbulence: 1 % intensity, so k = 1.5 (I U)^2, and a viscosity ratio of 10, so omega = k / (10 nu). Typical
    low-turbulence wind-tunnel values; the NACA tunnel's own turbulence level is not known to me.
  * Re = 2.45e5 with chord 1 and V1 = 1 gives nu = 1/245000: I use the standard NACA test Reynolds number.
  * The cyclic patches are made with createPatch from two plain patches (bottom_raw / top_raw) because gmshToFoam
    does not pair periodic faces (the first attempt with plain periodic groups failed), so this is not a style choice.
"""
from __future__ import annotations

import copy
import json
import math
import re
import shutil
from pathlib import Path

import numpy as np

from . import foam
from .geometry import BladeParams, blade_outline
from .mesh import MeshParams, build_mesh, make_domain

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE = ROOT / "case_template"


# ---------------------------------------------------------------------------- config
def deep_update(base: dict, upd: dict) -> dict:
    out = copy.deepcopy(base)
    for k, v in upd.items():
        if isinstance(v, dict) and isinstance(out.get(k), dict):
            out[k] = deep_update(out[k], v)
        else:
            out[k] = copy.deepcopy(v)
    return out


REQUIRED = {
    "blade": ["chord", "stagger_deg", "cl0"],
    "cascade": ["pitch"],
    "flow": ["V1", "beta1_deg", "reynolds", "turbulence_intensity", "viscosity_ratio"],
    "mesh": ["h_ref"],
    "solver": ["max_iter", "res_p", "res_U", "res_k", "res_omega"],
}


def validate_config(cfg: dict) -> None:
    for sec, keys in REQUIRED.items():
        if sec not in cfg:
            raise ValueError(f"config: missing section '{sec}'")
        for k in keys:
            if k not in cfg[sec]:
                raise ValueError(f"config: missing '{sec}.{k}'")
    f = cfg["flow"]
    if f["V1"] <= 0 or f["reynolds"] <= 0 or f["turbulence_intensity"] <= 0 or f["viscosity_ratio"] <= 0:
        raise ValueError("config: flow values must be positive")
    if not (0 < cfg["mesh"]["h_ref"] < 0.1):
        raise ValueError("config: mesh.h_ref outside the plausible range (0, 0.1)")
    dev = cfg.get("deviation", {})
    if dev.get("le_scale", 1.0) <= 0 or dev.get("thickness_scale", 1.0) <= 0:
        raise ValueError("config: le_scale and thickness_scale must be > 0")


def load_config(path) -> dict:
    path = Path(path)
    with open(path) as f:
        cfg = json.load(f)
    validate_config(cfg)
    cfg["_path"] = str(path.resolve())
    return cfg


def flow_derived(cfg: dict) -> dict:
    # inlet values from the dimensionless inputs; the equations are the standard Tu and nut/nu definitions
    f = cfg["flow"]
    chord = cfg["blade"]["chord"]
    V1 = f["V1"]
    b = math.radians(f["beta1_deg"])
    nu = V1 * chord / f["reynolds"]
    k = 1.5 * (f["turbulence_intensity"] * V1) ** 2
    nut = f["viscosity_ratio"] * nu
    omega = k / nut
    return {"nu": nu, "k": k, "omega": omega, "nut": nut, "UX": V1 * math.cos(b), "UY": V1 * math.sin(b)}


# ---------------------------------------------------------------------------- templates
def _fmt(v) -> str:
    return f"{v:.10g}" if isinstance(v, float) else str(v)


def fill_templates(case: Path, subs: dict) -> None:
    pat = re.compile(r"@([A-Z0-9_]+)@")
    for sub in ("0.orig", "constant", "system"):
        for f in (case / sub).iterdir():
            if not f.is_file():
                continue
            txt = f.read_text()
            txt = pat.sub(lambda m: _fmt(subs[m.group(1)]) if m.group(1) in subs else m.group(0), txt)
            left = pat.findall(txt)
            if left:
                raise ValueError(f"{f}: unfilled placeholders {sorted(set(left))}")
            f.write_text(txt)


def set_patch_types(case: Path, types: dict) -> None:
    """Edit constant/polyMesh/boundary: {patch: type} (e.g. front/back -> empty, blade -> wall)."""
    bfile = case / "constant/polyMesh/boundary"
    txt = bfile.read_text()
    for n, t in types.items():
        new, cnt = re.subn(r"(\b%s\s*\{[^{}]*?type\s+)\w+;([^{}]*?physicalType\s+)\w+;" % re.escape(n),
                           r"\g<1>%s;\g<2>%s;" % (t, t), txt, flags=re.S)
        if cnt != 1:
            raise RuntimeError(f"could not set patch '{n}' to type '{t}' in {bfile}")
        txt = new
    bfile.write_text(txt)


def remove_cell_zones(case: Path) -> None:
    """gmshToFoam turns the volume physical group into a cellZone + cellSet 'fluid'. The zone is
    not needed and makes 'simpleFoam -dry-run' abort on v2606 (dummy zone lookup), so drop it."""
    pm = case / "constant/polyMesh"
    for f in (pm / "cellZones", pm / "sets" / "fluid"):
        if f.exists():
            f.unlink()
    sets = pm / "sets"
    if sets.is_dir() and not any(sets.iterdir()):
        sets.rmdir()


# ---------------------------------------------------------------------------- build
def _safe_prepare(case: Path) -> None:
    """Remove an old case only if it was created by this code."""
    if case.exists():
        if not (case / "case_meta.json").exists() and any(case.iterdir()):
            raise RuntimeError(f"{case} exists, is not empty and was not created by cascade.case; "
                               "refusing to overwrite. Choose another --case or delete it yourself.")
        shutil.rmtree(case)
    case.mkdir(parents=True)


def parse_checkmesh(text: str) -> dict:
    out = {"mesh_ok": "Mesh OK" in text}
    m = re.search(r"^\s*cells:\s+(\d+)", text, re.M)
    out["n_cells"] = int(m.group(1)) if m else None
    m = re.search(r"Mesh non-orthogonality Max:\s*([\d.eE+-]+)\s+average:\s*([\d.eE+-]+)", text)
    if m:
        out["max_non_ortho"] = float(m.group(1))
        out["avg_non_ortho"] = float(m.group(2))
    m = re.search(r"Max skewness\s*=\s*([\d.eE+-]+)", text)
    out["max_skewness"] = float(m.group(1)) if m else None
    m = re.search(r"Max aspect ratio\s*=\s*([\d.eE+-]+)", text)
    out["max_aspect_ratio"] = float(m.group(1)) if m else None
    m = re.search(r"Failed\s+(\d+)\s+mesh checks", text)
    out["failed_checks"] = int(m.group(1)) if m else 0
    return out


def build_case(cfg: dict, case_dir, legacy_cyclic: bool = False, verbose: bool = False,
               name: str | None = None) -> dict:
    """Create the full case in case_dir (mesh included, ready for simpleFoam)."""
    validate_config(cfg)
    case = Path(case_dir).resolve()
    _safe_prepare(case)

    blade = BladeParams.from_config(cfg)
    mp = MeshParams.from_config(cfg)
    dom = make_domain(blade, cfg)
    fd = flow_derived(cfg)
    sv = cfg["solver"]

    # 1. template
    for sub in ("0.orig", "constant", "system"):
        shutil.copytree(TEMPLATE / sub, case / sub)
    if legacy_cyclic:
        cyc_b = cyc_t = ""
    else:
        cyc_b = f"            transform           translational;\n            separationVector    (0 {dom.pitch:.10g} 0);"
        cyc_t = f"            transform           translational;\n            separationVector    (0 {-dom.pitch:.10g} 0);"
    subs = {
        "NU": fd["nu"], "K": fd["k"], "OMEGA": fd["omega"], "NUT": fd["nut"],
        "UX": fd["UX"], "UY": fd["UY"],
        "MAX_ITER": int(sv["max_iter"]), "WRITE_INTERVAL": int(sv.get("write_interval", sv["max_iter"])),
        "RES_P": sv["res_p"], "RES_U": sv["res_U"], "RES_K": sv["res_k"], "RES_OMEGA": sv["res_omega"],
        "RELAX_U": sv.get("relax_U", 0.9), "RELAX_TURB": sv.get("relax_turb", 0.7),
        "CYCLIC_TRANSFORM_BOTTOM": cyc_b, "CYCLIC_TRANSFORM_TOP": cyc_t,
    }
    fill_templates(case, subs)

    # 2. mesh
    msh = case / "cascade.msh"
    mesh_meta = build_mesh(blade, mp, cfg, msh, verbose=verbose)

    # 3. OpenFOAM mesh
    foam.run(["gmshToFoam", str(msh)], case, "gmshToFoam")
    remove_cell_zones(case)
    set_patch_types(case, {"front": "empty", "back": "empty", "blade": "wall"})
    foam.run(["createPatch", "-overwrite"], case, "createPatch")
    foam.run(["checkMesh"], case, "checkMesh", check=False)
    cm = parse_checkmesh(foam.log_text(case, "checkMesh"))
    if not cm["mesh_ok"]:
        raise foam.FoamError(f"checkMesh did not report 'Mesh OK' (see {case / 'log.checkMesh'})")
    if cm["n_cells"] != mesh_meta["n_cells_expected"]:
        raise foam.FoamError(f"cell count mismatch: gmsh {mesh_meta['n_cells_expected']} vs OpenFOAM {cm['n_cells']}")

    # 4. initial fields
    shutil.copytree(case / "0.orig", case / "0")

    # 5. metadata for post-processing
    outline = blade_outline(blade)
    np.savetxt(case / "blade_outline.csv", outline["polygon"], delimiter=",", header="x,y", comments="")
    meta = {
        "name": name or cfg.get("name", case.name),
        "config": {k: v for k, v in cfg.items() if not k.startswith("_")},
        "flow_derived": fd,
        "domain": dom.to_dict(),
        "mesh": {**mesh_meta, **cm},
        "blade": {
            "camber_deg": blade.camber_deg, "stagger_eff_deg": blade.stagger_eff_deg,
            "inlet_metal_angle_deg": blade.inlet_metal_angle_deg,
            "outlet_metal_angle_deg": blade.outlet_metal_angle_deg,
        },
        "legacy_cyclic": legacy_cyclic,
    }
    (case / "case_meta.json").write_text(json.dumps(meta, indent=2))
    return meta


def load_meta(case) -> dict:
    p = Path(case) / "case_meta.json"
    if not p.exists():
        raise FileNotFoundError(f"{p} not found: case was not built by cascade.case.build_case")
    return json.loads(p.read_text())
